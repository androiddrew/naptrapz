"""Generate the keyword normalizer's Unicode 15.0.0 ASCII projection.

Run with Python 3.12 (Unicode 15.0.0):
    python tools/generate_unicode.py --out src/unicode_data.zig

This is the projection needed by naptrap's ASCII token regex, not a general
Unicode normalizer. It preserves separators, apostrophes, and digits (including
compatibility digits, which the tokenizer must reject).
"""
import argparse
import json
from pathlib import Path
import re
import unicodedata as ud

VERSION = "15.0.0"


def projection(cp):
    text = ud.normalize("NFKD", chr(cp).replace("’", "'"))
    text = "".join(c for c in text if not ud.combining(c)).lower()
    text = "".join(c if c in "abcdefghijklmnopqrstuvwxyz0123456789'" else " " for c in text)
    return re.sub(" +", " ", text)


def generate():
    if ud.unidata_version != VERSION:
        raise SystemExit(f"Need Unicode {VERSION}; this Python provides {ud.unidata_version}")
    entries = [(cp, projection(cp)) for cp in range(128, 0x110000)]
    entries = [(cp, value) for cp, value in entries if value != " "]
    rules = []
    i = 0
    while i < len(entries):
        first, value = entries[i]
        constant = linear = i + 1
        while constant < len(entries) and entries[constant] == (first + constant - i, value):
            constant += 1
        if len(value) == 1:
            while (linear < len(entries) and entries[linear][0] == first + linear - i
                   and len(entries[linear][1]) == 1
                   and ord(entries[linear][1]) == ord(value) + linear - i):
                linear += 1
        end = max(constant, linear)
        increment = linear > constant
        rules.append(f"    .{{ .first = 0x{first:x}, .last = 0x{entries[end - 1][0]:x}, "
                     f".value = {json.dumps(value)}, .increment = {str(increment).lower()} }},")
        i = end
    return ("//! Generated by tools/generate_unicode.py; do not edit by hand.\n"
            "//! NFKD -> remove nonzero combining classes -> lowercase -> ASCII token projection.\n"
            f'pub const unicode_version = "{VERSION}";\n\n'
            "pub const Rule = struct { first: u21, last: u21, value: []const u8, increment: bool };\n"
            f"// {len(entries)} non-default codepoints compressed into {len(rules)} ranges.\n"
            "pub const rules = [_]Rule{\n" + "\n".join(rules) + "\n};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--check", action="store_true", help="verify the checked-in source without writing")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if args.out.read_text() != generated:
            raise SystemExit(f"{args.out} does not match the Unicode {VERSION} generator")
    else:
        args.out.write_text(generated)
    print(f"{args.out}: Unicode {VERSION}, {len(generated)} source bytes")


if __name__ == "__main__":
    main()
